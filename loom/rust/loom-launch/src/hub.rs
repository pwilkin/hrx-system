//! Discovery of published Loom profiles on a model hub.
//!
//! Only the hub's public HTTP API is used. Authentication is read from the
//! environment and sent only when present: public repositories answer
//! unauthenticated reads, and gated ones report their own error instead of being
//! silently skipped. Every file read is pinned to one revision.

use crate::errors::{Error, ErrorKind, Result};
use crate::values::{arr, obj, str_value, strict_int, truthy};
use serde_json::{json, Map, Value};
use std::collections::HashMap;
use std::sync::Mutex;
use std::time::Duration;

pub const DEFAULT_ENDPOINT: &str = "https://huggingface.co";
/// Packages generated by the Loom porting workflow carry this tag.
pub const PROFILE_TAG: &str = "loom-serve";
const USER_AGENT: &str = "loom-launch/1";

/// Answers one GET with a status and the complete body.
pub trait Transport: Send + Sync {
    fn get(&self, url: &str, headers: &[(String, String)]) -> Result<(u16, Vec<u8>)>;
}

/// The network transport: ureq with rustls, following redirects (LFS files).
pub struct UreqTransport {
    agent: ureq::Agent,
}

impl UreqTransport {
    pub fn new(timeout: Duration) -> Self {
        let agent = ureq::AgentBuilder::new()
            .timeout_connect(Duration::from_secs(15).min(timeout))
            .timeout(timeout)
            .user_agent(USER_AGENT)
            .build();
        UreqTransport { agent }
    }
}

impl Transport for UreqTransport {
    fn get(&self, url: &str, headers: &[(String, String)]) -> Result<(u16, Vec<u8>)> {
        let mut request = self.agent.get(url);
        for (name, value) in headers {
            request = request.set(name, value);
        }
        let response = match request.call() {
            Ok(response) => response,
            Err(ureq::Error::Status(_, response)) => response,
            Err(ureq::Error::Transport(error)) => {
                return Err(Error::new(
                    ErrorKind::HubUnreachable,
                    format!("cannot reach {url}: {error}"),
                ))
            }
        };
        let status = response.status();
        let mut body = Vec::new();
        use std::io::Read;
        response
            .into_reader()
            .take(256 * 1024 * 1024)
            .read_to_end(&mut body)
            .map_err(|error| {
                Error::new(
                    ErrorKind::HubUnreachable,
                    format!("reading {url} failed: {error}"),
                )
            })?;
        Ok((status, body))
    }
}

/// One repository as the hub describes it.
#[derive(Clone, Debug, Default)]
pub struct HubModel {
    pub repo: String,
    /// Hub revision (`sha`) the listing observed, when reported.
    pub revision: Option<String>,
    pub tags: Vec<String>,
    pub pipeline_tag: Option<String>,
    pub last_modified: Option<String>,
    pub downloads: i64,
    pub likes: i64,
    pub gated: bool,
    /// Root names of the repository's files, when the listing asked for them.
    pub siblings: Vec<String>,
    /// The hub's own card metadata.
    pub card_data: Map<String, Value>,
}

impl HubModel {
    pub fn author(&self) -> &str {
        self.repo.split('/').next().unwrap_or(&self.repo)
    }

    pub fn short_name(&self) -> &str {
        match self.repo.split_once('/') {
            Some((_, name)) => name,
            None => &self.repo,
        }
    }

    /// True when every named file is a root file of the repository.
    pub fn has_file(&self, names: &[&str]) -> bool {
        if self.siblings.is_empty() {
            return false;
        }
        names
            .iter()
            .all(|name| self.siblings.iter().any(|s| s == name))
    }

    /// True when the hub's own metadata labels the repository as a Loom package.
    pub fn tagged_loom(&self) -> bool {
        self.tags
            .iter()
            .any(|tag| tag == "loom" || tag == PROFILE_TAG)
            || self
                .card_data
                .get("library_name")
                .and_then(Value::as_str)
                .is_some_and(|name| name.starts_with("loom"))
    }

    pub fn base_model(&self) -> Option<String> {
        if let Some(Value::String(value)) = self.card_data.get("base_model") {
            return Some(value.clone());
        }
        for tag in &self.tags {
            if let Some(rest) = tag.strip_prefix("base_model:") {
                return rest.split(':').next_back().map(str::to_string);
            }
        }
        None
    }

    /// Machine-readable form used by `--json` output.
    pub fn describe(&self) -> Value {
        json!({
            "repo": self.repo,
            "author": self.author(),
            "name": self.short_name(),
            "revision": self.revision,
            "pipeline_tag": self.pipeline_tag,
            "tags": self.tags,
            "base_model": self.base_model(),
            "last_modified": self.last_modified,
            "downloads": self.downloads,
            "likes": self.likes,
            "gated": self.gated,
            "files": self.siblings,
        })
    }

    pub fn from_entry(entry: &Value) -> Option<HubModel> {
        let entry = entry.as_object()?;
        let repo = str_value(entry.get("id").unwrap_or(&Value::Null))
            .or_else(|| str_value(entry.get("modelId").unwrap_or(&Value::Null)))?
            .to_string();
        let field = |name: &str| {
            entry
                .get(name)
                .and_then(|v| str_value(v))
                .map(str::to_string)
        };
        let tags = arr(entry.get("tags").unwrap_or(&Value::Null))
            .iter()
            .filter_map(|tag| tag.as_str().map(str::to_string))
            .collect();
        let siblings = arr(entry.get("siblings").unwrap_or(&Value::Null))
            .iter()
            .filter_map(|sibling| {
                sibling
                    .get("rfilename")
                    .and_then(Value::as_str)
                    .map(str::to_string)
            })
            .collect();
        Some(HubModel {
            repo,
            revision: field("sha"),
            tags,
            pipeline_tag: field("pipeline_tag"),
            last_modified: field("lastModified"),
            downloads: entry.get("downloads").and_then(strict_int).unwrap_or(0),
            likes: entry.get("likes").and_then(strict_int).unwrap_or(0),
            gated: entry.get("gated").map(truthy).unwrap_or(false),
            siblings,
            card_data: obj(entry.get("cardData").unwrap_or(&Value::Null)).clone(),
        })
    }
}

/// A model-hub client with an injectable transport for tests.
pub struct Hub {
    pub endpoint: String,
    token: Option<String>,
    transport: Box<dyn Transport>,
    json_cache: Mutex<HashMap<String, Value>>,
    raw_cache: Mutex<HashMap<(String, String, String), Vec<u8>>>,
}

/// Search filters for [`Hub::search`].
#[derive(Clone, Debug, Default)]
pub struct SearchQuery {
    pub query: Option<String>,
    pub author: Option<String>,
    pub tags: Vec<String>,
    pub limit: usize,
    pub with_files: bool,
}

impl Hub {
    /// A hub at `endpoint` (or `$LOOM_HUB_ENDPOINT`, or the default), with the
    /// token from `$HF_TOKEN`/`$HUGGING_FACE_HUB_TOKEN` unless one is given.
    pub fn new(endpoint: Option<&str>, timeout: Duration) -> Hub {
        Hub::with_transport(endpoint, None, Box::new(UreqTransport::new(timeout)))
    }

    pub fn with_transport(
        endpoint: Option<&str>,
        token: Option<String>,
        transport: Box<dyn Transport>,
    ) -> Hub {
        let endpoint = endpoint
            .filter(|e| !e.is_empty())
            .map(str::to_string)
            .or_else(|| {
                std::env::var("LOOM_HUB_ENDPOINT")
                    .ok()
                    .filter(|e| !e.is_empty())
            })
            .unwrap_or_else(|| DEFAULT_ENDPOINT.to_string());
        let token = match token {
            Some(token) => Some(token),
            None => std::env::var("HF_TOKEN")
                .ok()
                .filter(|t| !t.is_empty())
                .or_else(|| {
                    std::env::var("HUGGING_FACE_HUB_TOKEN")
                        .ok()
                        .filter(|t| !t.is_empty())
                }),
        };
        Hub {
            endpoint: endpoint.trim_end_matches('/').to_string(),
            token: token.filter(|t| !t.is_empty()),
            transport,
            json_cache: Mutex::new(HashMap::new()),
            raw_cache: Mutex::new(HashMap::new()),
        }
    }

    pub fn is_default_endpoint(&self) -> bool {
        self.endpoint == DEFAULT_ENDPOINT
    }

    fn headers(&self) -> Vec<(String, String)> {
        let mut headers = vec![
            ("User-Agent".to_string(), USER_AGENT.to_string()),
            ("Accept".to_string(), "application/json".to_string()),
        ];
        if let Some(token) = &self.token {
            headers.push(("Authorization".to_string(), format!("Bearer {token}")));
        }
        headers
    }

    fn fetch(&self, url: &str) -> Result<Vec<u8>> {
        let (status, body) = self.transport.get(url, &self.headers())?;
        match status {
            401 | 403 => Err(Error::new(
                ErrorKind::HubAuth,
                format!(
                    "{url} does not exist or requires credentials (the hub answers both with \
                     HTTP {status}): check the name, then run `hf auth login`, or set HF_TOKEN \
                     for the account that was granted access"
                ),
            )),
            404 => Err(Error::new(
                ErrorKind::HubNotFound,
                format!("{url} was not found"),
            )),
            status if status >= 400 => {
                let end = body.len().min(200);
                let detail = String::from_utf8_lossy(&body[..end]).trim().to_string();
                Err(Error::hub(format!(
                    "{url} answered HTTP {status}: {detail}"
                )))
            }
            _ => Ok(body),
        }
    }

    fn fetch_json(&self, url: &str) -> Result<Value> {
        if let Some(cached) = self.json_cache.lock().unwrap().get(url) {
            return Ok(cached.clone());
        }
        let body = self.fetch(url)?;
        let document: Value = serde_json::from_slice(&body)
            .map_err(|error| Error::hub(format!("{url} did not return JSON: {error}")))?;
        self.json_cache
            .lock()
            .unwrap()
            .insert(url.to_string(), document.clone());
        Ok(document)
    }

    /// Lists matching repositories, newest activity first. An owner prefix
    /// ("loom-fun/") is accepted as a query and becomes an author filter.
    pub fn search(&self, search: &SearchQuery) -> Result<Vec<HubModel>> {
        let mut query = search.query.clone().filter(|q| !q.is_empty());
        let mut author = search.author.clone().filter(|a| !a.is_empty());
        if let Some(text) = &query {
            if text.ends_with('/') && author.is_none() {
                let candidate = text.trim_end_matches('/');
                if looks_like_author(candidate) {
                    author = Some(candidate.to_string());
                    query = None;
                }
            }
        }
        let mut parameters: Vec<(String, String)> = vec![
            ("limit".into(), search.limit.clamp(1, 1000).to_string()),
            ("sort".into(), "lastModified".into()),
            ("direction".into(), "-1".into()),
        ];
        if search.with_files {
            parameters.push(("full".into(), "true".into()));
        }
        if let Some(query) = query {
            parameters.push(("search".into(), query));
        }
        if let Some(author) = author {
            parameters.push(("author".into(), author));
        }
        for tag in &search.tags {
            parameters.push(("filter".into(), tag.clone()));
        }
        let url = format!("{}/api/models?{}", self.endpoint, urlencode(&parameters));
        let document = self.fetch_json(&url)?;
        let Value::Array(entries) = document else {
            return Err(Error::hub(format!(
                "{url} did not return a repository list"
            )));
        };
        Ok(entries.iter().filter_map(HubModel::from_entry).collect())
    }

    /// Reads one repository's metadata and root file names.
    pub fn model(&self, repo: &str) -> Result<HubModel> {
        let url = format!(
            "{}/api/models/{}?full=true",
            self.endpoint,
            quote(repo, "/")
        );
        let document = self.fetch_json(&url)?;
        if !document.is_object() {
            return Err(Error::hub(format!("{repo} does not describe a repository")));
        }
        HubModel::from_entry(&document)
            .ok_or_else(|| Error::hub(format!("{repo} does not describe a repository")))
    }

    /// Lists repositories that publish an installable Loom profile: a root
    /// `model.json`, or (when the hub did not list files) a Loom tag.
    pub fn profiles(
        &self,
        query: Option<&str>,
        author: Option<&str>,
        limit: usize,
        tags: &[String],
    ) -> Result<Vec<HubModel>> {
        let found = self.search(&SearchQuery {
            query: query.map(str::to_string),
            author: author.map(str::to_string),
            tags: tags.to_vec(),
            limit,
            with_files: true,
        })?;
        Ok(found
            .into_iter()
            .filter(|model| {
                model.has_file(&["model.json"])
                    || (model.siblings.is_empty() && model.tagged_loom())
            })
            .collect())
    }

    /// Reads one file at a pinned revision (`main` when none is given).
    pub fn raw(&self, repo: &str, path: &str, revision: Option<&str>) -> Result<Vec<u8>> {
        let revision = revision.filter(|r| !r.is_empty()).unwrap_or("main");
        let key = (repo.to_string(), revision.to_string(), path.to_string());
        if let Some(cached) = self.raw_cache.lock().unwrap().get(&key) {
            return Ok(cached.clone());
        }
        let url = format!(
            "{}/{}/resolve/{}/{}",
            self.endpoint,
            quote(repo, "/"),
            quote(revision, ""),
            quote(path, "/")
        );
        let body = self.fetch(&url)?;
        self.raw_cache.lock().unwrap().insert(key, body.clone());
        Ok(body)
    }

    /// Reads one file, treating an absent file (404) as empty.
    pub fn raw_optional(&self, repo: &str, path: &str, revision: Option<&str>) -> Result<Vec<u8>> {
        match self.raw(repo, path, revision) {
            Ok(body) => Ok(body),
            Err(error) if error.kind == ErrorKind::HubNotFound => Ok(Vec::new()),
            Err(error) => Err(error),
        }
    }

    /// Reads one JSON object, treating an absent or invalid file as empty.
    pub fn json_optional(
        &self,
        repo: &str,
        path: &str,
        revision: Option<&str>,
    ) -> Result<Map<String, Value>> {
        let body = self.raw_optional(repo, path, revision)?;
        if body.is_empty() {
            return Ok(Map::new());
        }
        Ok(crate::values::parse_object(&body))
    }
}

fn looks_like_author(name: &str) -> bool {
    !name.is_empty()
        && name
            .chars()
            .all(|c| c.is_alphanumeric() || "-_.".contains(c))
}

/// Percent-encodes like Python's `urllib.parse.quote(text, safe)`.
pub fn quote(text: &str, safe: &str) -> String {
    let mut out = String::new();
    for byte in text.bytes() {
        let c = byte as char;
        if c.is_ascii_alphanumeric() || "_.-~".contains(c) || (c.is_ascii() && safe.contains(c)) {
            out.push(c);
        } else {
            out.push_str(&format!("%{byte:02X}"));
        }
    }
    out
}

/// `urllib.parse.urlencode`: `quote_plus` keys and values joined with `&`.
pub fn urlencode(parameters: &[(String, String)]) -> String {
    let plus = |text: &str| quote(text, " ").replace(' ', "+");
    parameters
        .iter()
        .map(|(key, value)| format!("{}={}", plus(key), plus(value)))
        .collect::<Vec<_>>()
        .join("&")
}

#[cfg(test)]
pub(crate) mod tests {
    use super::*;
    use std::sync::{Arc, Mutex};

    pub(crate) type Calls = Arc<Mutex<Vec<(String, Vec<(String, String)>)>>>;

    /// A transport answering by URL fragment; unknown URLs are 404.
    pub(crate) struct FragmentTransport {
        pub routes: Vec<(String, u16, Vec<u8>)>,
        pub calls: Calls,
    }

    impl FragmentTransport {
        pub(crate) fn new(routes: Vec<(&str, u16, Value)>) -> Self {
            FragmentTransport {
                routes: routes
                    .into_iter()
                    .map(|(fragment, status, body)| {
                        let bytes = match body {
                            Value::String(text) => text.into_bytes(),
                            other => serde_json::to_vec(&other).unwrap(),
                        };
                        (fragment.to_string(), status, bytes)
                    })
                    .collect(),
                calls: Arc::new(Mutex::new(Vec::new())),
            }
        }
    }

    impl Transport for FragmentTransport {
        fn get(&self, url: &str, headers: &[(String, String)]) -> Result<(u16, Vec<u8>)> {
            self.calls
                .lock()
                .unwrap()
                .push((url.to_string(), headers.to_vec()));
            for (fragment, status, body) in &self.routes {
                if url.contains(fragment.as_str()) {
                    return Ok((*status, body.clone()));
                }
            }
            Ok((404, Vec::new()))
        }
    }

    pub(crate) fn search_document() -> Value {
        json!([
            {
                "id": "loom-fun/a-loom",
                "sha": "a".repeat(40),
                "pipeline_tag": "text-generation",
                "tags": ["loom", "loom-serve", "base_model:org/a-GGUF"],
                "downloads": 3,
                "likes": 1,
                "gated": false,
                "cardData": {"base_model": "org/a-GGUF"},
                "siblings": [
                    {"rfilename": "model.json"},
                    {"rfilename": "info.json"},
                    {"rfilename": "README.md"}
                ]
            },
            {
                "id": "somebody/catalog",
                "sha": "b".repeat(40),
                "tags": ["loom-serve"],
                "siblings": [{"rfilename": "catalog.json"}]
            }
        ])
    }

    fn hub(routes: Vec<(&str, u16, Value)>) -> (Hub, Calls) {
        let transport = FragmentTransport::new(routes);
        let calls = transport.calls.clone();
        (
            Hub::with_transport(
                Some(DEFAULT_ENDPOINT),
                Some(String::new()),
                Box::new(transport),
            ),
            calls,
        )
    }

    fn query(text: &str) -> SearchQuery {
        SearchQuery {
            query: Some(text.to_string()),
            limit: 50,
            with_files: true,
            ..Default::default()
        }
    }

    #[test]
    fn search_returns_models_with_files_and_base_model() {
        let (hub, _) = hub(vec![("api/models", 200, search_document())]);
        let models = hub.search(&query("a-loom")).unwrap();
        let repos: Vec<_> = models.iter().map(|m| m.repo.as_str()).collect();
        assert_eq!(repos, ["loom-fun/a-loom", "somebody/catalog"]);
        assert!(models[0].has_file(&["model.json", "info.json"]));
        assert!(!models[0].has_file(&["catalog.json"]));
        assert_eq!(models[0].base_model().as_deref(), Some("org/a-GGUF"));
        assert_eq!(models[0].revision.as_deref(), Some("a".repeat(40).as_str()));
    }

    #[test]
    fn owner_prefix_becomes_an_author_filter() {
        let (hub, calls) = hub(vec![("api/models", 200, search_document())]);
        hub.search(&query("loom-fun/")).unwrap();
        let url = calls.lock().unwrap()[0].0.clone();
        assert!(url.contains("author=loom-fun"), "{url}");
        assert!(!url.contains("search="), "{url}");
    }

    #[test]
    fn profiles_require_a_root_model_card() {
        let (hub, _) = hub(vec![("api/models", 200, search_document())]);
        let profiles = hub.profiles(Some("loom"), None, 50, &[]).unwrap();
        let repos: Vec<_> = profiles.iter().map(|m| m.repo.as_str()).collect();
        assert_eq!(repos, ["loom-fun/a-loom"]);
    }

    #[test]
    fn raw_reads_a_pinned_revision_and_caches_it() {
        let (hub, calls) = hub(vec![("model.json", 200, json!("{}"))]);
        let revision = "c".repeat(40);
        assert_eq!(
            hub.raw("loom-fun/a-loom", "model.json", Some(&revision))
                .unwrap(),
            b"{}"
        );
        assert_eq!(
            hub.raw("loom-fun/a-loom", "model.json", Some(&revision))
                .unwrap(),
            b"{}"
        );
        let calls = calls.lock().unwrap();
        assert_eq!(calls.len(), 1);
        assert!(calls[0]
            .0
            .contains(&format!("/resolve/{revision}/model.json")));
    }

    #[test]
    fn missing_and_invalid_files_read_as_empty() {
        let (hub, _) = hub(vec![("info.json", 200, json!("not json"))]);
        assert!(hub
            .raw_optional("loom-fun/a-loom", "README.md", None)
            .unwrap()
            .is_empty());
        assert!(hub
            .json_optional("loom-fun/a-loom", "info.json", None)
            .unwrap()
            .is_empty());
    }

    #[test]
    fn credentials_failure_explains_what_to_do() {
        let (hub, _) = hub(vec![("api/models", 401, json!("unauthorized"))]);
        let error = hub.search(&query("absent")).unwrap_err();
        assert_eq!(error.kind, ErrorKind::HubAuth);
        assert!(error.message.contains("hf auth login"));
    }

    #[test]
    fn a_token_is_sent_only_when_configured() {
        let transport = FragmentTransport::new(vec![("api/models", 200, search_document())]);
        let calls = transport.calls.clone();
        let hub = Hub::with_transport(None, Some("secret".into()), Box::new(transport));
        hub.search(&query("a-loom")).unwrap();
        let headers = calls.lock().unwrap()[0].1.clone();
        assert!(headers.contains(&("Authorization".into(), "Bearer secret".into())));
        let (anonymous, calls) = hub_with_empty_token();
        anonymous.search(&query("a-loom")).unwrap();
        assert!(!calls.lock().unwrap()[0]
            .1
            .iter()
            .any(|(name, _)| name == "Authorization"));
    }

    fn hub_with_empty_token() -> (Hub, Calls) {
        hub(vec![("api/models", 200, search_document())])
    }

    #[test]
    fn server_failure_is_reported_with_its_status() {
        let (hub, _) = hub(vec![("api/models", 500, json!("boom"))]);
        let error = hub.search(&query("absent")).unwrap_err();
        assert!(error.message.contains("HTTP 500"));
    }

    #[test]
    fn model_detail_requires_a_repository_object() {
        let (hub, _) = hub(vec![("api/models/", 200, json!(["not", "an", "object"]))]);
        let error = hub.model("loom-fun/a-loom").unwrap_err();
        assert!(error.message.contains("does not describe a repository"));
    }

    #[test]
    fn url_encoding_matches_urllib() {
        assert_eq!(quote("loom-fun/a b", "/"), "loom-fun/a%20b");
        assert_eq!(
            urlencode(&[("search".into(), "a b/c".into())]),
            "search=a+b%2Fc"
        );
    }
}
